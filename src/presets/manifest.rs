//! `presets/profiles.toml`: the committed result of `rank`, plus the small TOML
//! subset (basic strings, string arrays, `[[table]]` headers) this crate reads.

use crate::ffi::{Error, Result};
use crate::presets::rank::{rank, Profile, PROFILES};
use crate::presets::Packs;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Manifest {
    pub profiles: Vec<Profile>,
}

impl Manifest {
    /// Rank every profile. Paths are stored relative to the Cream of the Crop root,
    /// so the file is portable across cache locations.
    pub fn generate(packs: &Packs, n: usize) -> Result<Manifest> {
        let mut profiles = Vec::new();
        for name in PROFILES {
            let mut p = rank(packs, name, n)?;
            for f in &mut p.presets {
                *f = f
                    .strip_prefix(&packs.cotc)
                    .map_err(|_| Error::msg(format!("{} is outside {}", f.display(), packs.cotc.display())))?
                    .to_path_buf();
            }
            profiles.push(p);
        }
        Ok(Manifest { profiles })
    }

    pub fn profile(&self, name: &str) -> Option<&Profile> {
        self.profiles.iter().find(|p| p.name == name)
    }

    pub fn save(&self, path: &Path) -> Result<()> {
        let mut s = String::from("# Generated by `projectmp4 rank`. Paths are relative to the Cream of the Crop root.\n");
        for p in &self.profiles {
            s.push_str("\n[[profile]]\nname = ");
            s.push_str(&quote(&p.name));
            s.push_str("\npresets = [\n");
            for f in &p.presets {
                let f = f.to_str().ok_or_else(|| Error::msg(format!("non-UTF-8 path {}", f.display())))?;
                s.push_str("  ");
                s.push_str(&quote(f));
                s.push_str(",\n");
            }
            s.push_str("]\n");
        }
        std::fs::write(path, s).map_err(|e| Error::msg(format!("write {}: {e}", path.display())))
    }

    pub fn load(path: &Path) -> Result<Manifest> {
        let text = std::fs::read_to_string(path)
            .map_err(|e| Error::msg(format!("read {}: {e}", path.display())))?;
        Self::parse(&text)
    }

    pub fn parse(text: &str) -> Result<Manifest> {
        let mut profiles: Vec<Profile> = Vec::new();
        let mut in_array = false;
        for line in text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')) {
            if in_array {
                if line == "]" {
                    in_array = false;
                    continue;
                }
                let (s, rest) = unquote(line)?;
                if rest.trim() != "," {
                    return Err(Error::msg(format!("profiles.toml: bad array entry {line:?}")));
                }
                profiles
                    .last_mut()
                    .ok_or_else(|| Error::msg("profiles.toml: array outside [[profile]]"))?
                    .presets
                    .push(PathBuf::from(s));
            } else if line == "[[profile]]" {
                profiles.push(Profile { name: String::new(), presets: Vec::new() });
            } else if let Some(v) = line.strip_prefix("name") {
                let v = v.trim_start().strip_prefix('=').ok_or_else(|| Error::msg("profiles.toml: bad name line"))?;
                let (s, rest) = unquote(v.trim())?;
                if !rest.trim().is_empty() {
                    return Err(Error::msg(format!("profiles.toml: trailing text {rest:?}")));
                }
                profiles.last_mut().ok_or_else(|| Error::msg("profiles.toml: name outside [[profile]]"))?.name = s;
            } else if line.replace(' ', "") == "presets=[" {
                in_array = true;
            } else {
                return Err(Error::msg(format!("profiles.toml: unrecognised line {line:?}")));
            }
        }
        if in_array {
            return Err(Error::msg("profiles.toml: unterminated presets array"));
        }
        if profiles.iter().any(|p| p.name.is_empty()) {
            return Err(Error::msg("profiles.toml: [[profile]] without a name"));
        }
        Ok(Manifest { profiles })
    }
}

/// TOML basic string with every control character escaped.
pub(crate) fn quote(s: &str) -> String {
    let mut o = String::with_capacity(s.len() + 2);
    o.push('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => o.push_str(&format!("\\u{:04X}", c as u32)),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// Parse a leading TOML basic string; returns it and the text after the closing quote.
pub(crate) fn unquote(s: &str) -> Result<(String, &str)> {
    let body = s.strip_prefix('"').ok_or_else(|| Error::msg(format!("expected a quoted string, got {s:?}")))?;
    let mut out = String::new();
    let mut it = body.char_indices();
    while let Some((i, c)) = it.next() {
        match c {
            '"' => return Ok((out, &body[i + 1..])),
            '\\' => match it.next().map(|(_, e)| e) {
                Some('"') => out.push('"'),
                Some('\\') => out.push('\\'),
                Some('n') => out.push('\n'),
                Some('r') => out.push('\r'),
                Some('t') => out.push('\t'),
                Some('b') => out.push('\u{8}'),
                Some('f') => out.push('\u{c}'),
                Some('u') => {
                    let hex: String = (0..4).filter_map(|_| it.next().map(|(_, h)| h)).collect();
                    let c = u32::from_str_radix(&hex, 16)
                        .ok()
                        .and_then(char::from_u32)
                        .ok_or_else(|| Error::msg(format!("bad \\u escape {hex:?}")))?;
                    out.push(c);
                }
                other => return Err(Error::msg(format!("bad escape {other:?} in {s:?}"))),
            },
            c => out.push(c),
        }
    }
    Err(Error::msg(format!("unterminated string {s:?}")))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn manifest_round_trips_awkward_names() {
        let m = Manifest {
            profiles: vec![
                Profile {
                    name: "deathstep".into(),
                    presets: vec![
                        PathBuf::from("Reaction/Feedback/$$$ Royal - Mashup (452).milk"),
                        PathBuf::from("Geometric/q\"uote\\back/tab\there \u{e9}\u{4e2d}.milk"),
                    ],
                },
                Profile { name: "empty".into(), presets: vec![] },
            ],
        };
        let p = std::env::temp_dir().join(format!("projectmp4-manifest-{}.toml", std::process::id()));
        m.save(&p).unwrap();
        let text = std::fs::read_to_string(&p).unwrap();
        let back = Manifest::load(&p).unwrap();
        let _ = std::fs::remove_file(&p);
        assert!(text.contains("\\\"") && text.contains("\\t"), "escapes were not written: {text}");
        assert_eq!(back, m);
        assert_eq!(back.profile("deathstep").unwrap().presets.len(), 2);
    }

    #[test]
    fn malformed_manifest_is_an_error_not_a_panic() {
        for bad in ["name = \"x\"\n", "[[profile]]\npresets = [\n  \"a\",\n", "[[profile]]\nname = \"x\" junk\n", "[[profile]]\npresets = [\n  \"a\"\n]\n", "[[profile]]\nname = \"a\\q\"\n"] {
            assert!(Manifest::parse(bad).is_err(), "accepted {bad:?}");
        }
    }
}
