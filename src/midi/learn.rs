//! `midi-learn`: list sources, monitor traffic, and capture a profile skeleton
//! by asking the user to touch each control in turn.

use std::collections::HashSet;
use std::fmt::Write as _;
use std::path::Path;
use std::time::{Duration, Instant};

use crate::ffi::{Error, Result};
use crate::midi::MidiIn;

const POLL: Duration = Duration::from_millis(5);

/// One incoming message as a line a human can compare against a spec sheet.
/// Fixed-width columns: kind (9), channel (5), number, value.
pub fn decode(msg: [u8; 3]) -> String {
    let [status, d1, d2] = msg;
    let ch = format!("ch{}", (status & 0x0F) + 1);
    let (kind, number, value) = match status & 0xF0 {
        0x80 => ("note-off", format!("0x{d1:02x}"), format!("vel {d2}")),
        0x90 => ("note-on", format!("0x{d1:02x}"), format!("vel {d2}")),
        0xA0 => ("aftertouch", format!("0x{d1:02x}"), format!("val {d2}")),
        0xB0 => ("cc", format!("0x{d1:02x}"), format!("val {d2}")),
        0xC0 => ("program", format!("0x{d1:02x}"), String::new()),
        0xD0 => ("aftertouch", format!("0x{d1:02x}"), String::new()),
        0xE0 => (
            "pitch-bend",
            "----".to_string(),
            format!("val {}", u16::from(d1 & 0x7F) | (u16::from(d2 & 0x7F) << 7)),
        ),
        _ => ("other", format!("0x{d1:02x}"), format!("0x{d2:02x}")),
    };
    format!("{kind:<9} {ch:<4} {number}  {value}").trim_end().to_string()
}

/// The address half, in the form a profile line uses: "0x94:0x17".
pub fn address(msg: [u8; 3]) -> String {
    format!("0x{:02x}:0x{:02x}", msg[0], msg[1])
}

/// Spots CC pairs that look like a 14-bit control: CC `n` (< 0x20) and CC
/// `n + 0x20` on the same channel. Each pair is reported once.
#[derive(Default)]
pub struct PairWatch {
    seen: HashSet<(u8, u8)>,
    flagged: HashSet<(u8, u8)>,
}

impl PairWatch {
    pub fn observe(&mut self, msg: [u8; 3]) -> Option<String> {
        if msg[0] & 0xF0 != 0xB0 {
            return None;
        }
        let ch = msg[0] & 0x0F;
        let n = msg[1] & 0x7F;
        self.seen.insert((ch, n));
        let msb = if (0x20..0x40).contains(&n) { n - 0x20 } else { n };
        let lsb = msb + 0x20;
        if msb >= 0x20 || !self.seen.contains(&(ch, msb)) || !self.seen.contains(&(ch, lsb)) {
            return None;
        }
        if !self.flagged.insert((ch, msb)) {
            return None;
        }
        Some(format!(
            "note: ch{} CC 0x{msb:02x} + CC 0x{lsb:02x} look like a 14-bit pair (MSB/LSB)",
            ch + 1
        ))
    }
}

/// Print every visible MIDI source and return them.
pub fn list() -> Result<Vec<String>> {
    let ports = MidiIn::ports()?;
    if ports.is_empty() {
        println!("no MIDI sources");
    }
    for p in &ports {
        println!("{p}");
    }
    Ok(ports)
}

/// Monitor: print a decoded line for every message until `until` elapses.
/// Returns what it saw, in order.
pub fn monitor(port: Option<&str>, until: Duration) -> Result<Vec<[u8; 3]>> {
    let mut m = MidiIn::open(port)?;
    monitor_from(&mut m, until)
}

/// [`monitor`] on an already-open input.
pub fn monitor_from(m: &mut MidiIn, until: Duration) -> Result<Vec<[u8; 3]>> {
    let deadline = Instant::now() + until;
    let mut seen = Vec::new();
    let mut pairs = PairWatch::default();
    while Instant::now() < deadline {
        m.drain(|msg| {
            println!("{}", decode(msg));
            if let Some(note) = pairs.observe(msg) {
                println!("{note}");
            }
            seen.push(msg);
        });
        std::thread::sleep(POLL);
    }
    let dropped = m.overflowed();
    if dropped > 0 {
        eprintln!("note: {dropped} messages were dropped (queue full)");
    }
    Ok(seen)
}

/// Capture: for each control, prompt on stderr, wait for the first message
/// that is a real press or movement, and record its address. Writes a profile
/// to `out`. `verbs` is parallel to `controls`.
pub fn capture(port: Option<&str>, controls: &[&str], verbs: &[&str], out: &Path) -> Result<()> {
    let mut m = MidiIn::open(port)?;
    let name = MidiIn::ports()?
        .into_iter()
        .find(|n| port.is_none_or(|p| n.contains(p)))
        .unwrap_or_default();
    capture_from(&mut m, &name, controls, verbs, out, Duration::from_secs(60))
}

/// [`capture`] on an already-open input; `timeout` bounds the wait per control.
pub fn capture_from(
    m: &mut MidiIn,
    port_name: &str,
    controls: &[&str],
    verbs: &[&str],
    out: &Path,
    timeout: Duration,
) -> Result<()> {
    if controls.len() != verbs.len() {
        return Err(Error::msg(format!(
            "{} controls but {} verbs; they must be parallel",
            controls.len(),
            verbs.len()
        )));
    }
    let mut text = String::new();
    let _ = writeln!(text, "# generated by midi-learn from {port_name} on {}", today());
    let _ = writeln!(text, "name = \"{}\"\n", port_name.replace('"', "'"));

    let mut taken: HashSet<String> = HashSet::new();
    // `drain` empties the queue; messages after the one we take belong to later controls.
    let mut pending: std::collections::VecDeque<[u8; 3]> = std::collections::VecDeque::new();
    for (control, verb) in controls.iter().zip(verbs) {
        eprintln!("touch: {control}");
        let deadline = Instant::now() + timeout;
        let mut found: Option<String> = None;
        while found.is_none() {
            m.drain(|msg| pending.push_back(msg));
            while let Some(msg) = pending.pop_front() {
                let release = msg[0] & 0xF0 == 0x80 || (msg[0] & 0xF0 == 0x90 && msg[2] == 0);
                let addr = address(msg);
                if !release && !taken.contains(&addr) {
                    found = Some(addr);
                    break;
                }
            }
            if found.is_some() {
                break;
            }
            if Instant::now() >= deadline {
                return Err(Error::msg(format!(
                    "timed out waiting for a message from {control:?} on {port_name:?}"
                )));
            }
            std::thread::sleep(POLL);
        }
        if let Some(addr) = found {
            eprintln!("  got {addr}");
            let _ = writeln!(text, "{addr} = {verb}");
            taken.insert(addr);
        }
    }
    std::fs::write(out, text)
        .map_err(|e| Error::msg(format!("cannot write profile {}: {e}", out.display())))
}

/// Today's UTC date as YYYY-MM-DD (days-since-epoch to civil date).
fn today() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let z = (secs / 86_400) as i64 + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    format!("{y:04}-{m:02}-{d:02}")
}
