use midir::{MidiOutput, MidiOutputConnection};
use projectmp4::midi::learn::{address, capture_from, decode, PairWatch};
use projectmp4::midi::MidiIn;
use std::time::{Duration, Instant};

#[path = "common/tmp.rs"]
mod tmp;
use tmp::Tmp;

fn unique(test: &str) -> String {
    format!("projectmp4-learn-{}-{test}", std::process::id())
}

// A virtual *input* is a destination, not a source: `MidiIn::open` cannot see
// it, so these tests drive `capture_from` on an `open_virtual` handle.
fn sender(name: &str) -> MidiOutputConnection {
    let out = MidiOutput::new("learn-test-out").unwrap();
    let deadline = Instant::now() + Duration::from_secs(3);
    loop {
        if let Some(p) = out
            .ports()
            .into_iter()
            .find(|p| out.port_name(p).unwrap_or_default().contains(name))
        {
            return out.connect(&p, "test").unwrap();
        }
        assert!(Instant::now() < deadline, "virtual port {name} never appeared");
        std::thread::sleep(Duration::from_millis(10));
    }
}

#[test]
fn decode_names_each_message_kind() {
    assert_eq!(decode([0x94, 0x17, 127]), "note-on   ch5  0x17  vel 127");
    assert_eq!(decode([0x80, 0x3C, 0]), "note-off  ch1  0x3c  vel 0");
    assert_eq!(decode([0xB0, 0x09, 64]), "cc        ch1  0x09  val 64");
    assert!(decode([0xC2, 0x05, 0]).starts_with("program   ch3  0x05"));
    assert!(decode([0xE0, 0x00, 0x40]).starts_with("pitch-bend"));
    assert!(decode([0xA0, 0x10, 9]).starts_with("aftertouch"));
}

#[test]
fn decode_reports_one_indexed_channels() {
    assert!(decode([0x94, 1, 1]).contains("ch5"));
    assert!(decode([0x9F, 1, 1]).contains("ch16"));
}

#[test]
fn address_matches_the_profile_line_format() {
    assert_eq!(address([0x94, 0x17, 0x7F]), "0x94:0x17");
    assert_eq!(address([0x90, 0x02, 0x7F]), "0x90:0x02");
    assert_eq!(address([0xBF, 0x1A, 1]), "0xbf:0x1a");
}

#[test]
fn a_fourteen_bit_pair_is_flagged() {
    let mut w = PairWatch::default();
    assert!(w.observe([0xB0, 0x09, 1]).is_none());
    let note = w.observe([0xB0, 0x29, 1]).expect("pair should be flagged");
    assert!(note.contains("14-bit"), "{note}");
    // flagged once only
    assert!(w.observe([0xB0, 0x29, 2]).is_none());

    let mut w = PairWatch::default();
    assert!(w.observe([0xB0, 0x09, 1]).is_none());
    assert!(w.observe([0xB1, 0x29, 1]).is_none(), "different channels are not a pair");
}

#[test]
fn capture_ignores_note_off_and_zero_velocity() {
    let n = unique("noteoff");
    let mut m = MidiIn::open_virtual(&n).unwrap();
    let mut s = sender(&n);
    s.send(&[0x80, 0x05, 0x40]).unwrap();
    s.send(&[0x90, 0x06, 0x00]).unwrap();
    s.send(&[0x90, 0x07, 0x7F]).unwrap();
    let scratch = Tmp::new("learn-noteoff");
    let out = scratch.0.join("profile.toml");
    capture_from(&mut m, &n, &["play"], &["transport-toggle"], &out, Duration::from_secs(3)).unwrap();
    let text = std::fs::read_to_string(&out).unwrap();
    assert!(text.contains("0x90:0x07 = transport-toggle"), "{text}");
    assert!(!text.contains("0x80:0x05") && !text.contains("0x90:0x06"), "{text}");
}

#[test]
fn capture_ignores_a_repeat_of_an_address_already_taken() {
    let n = unique("repeat");
    let mut m = MidiIn::open_virtual(&n).unwrap();
    let mut s = sender(&n);
    s.send(&[0xB0, 0x1A, 10]).unwrap();
    s.send(&[0xB0, 0x1A, 11]).unwrap();
    s.send(&[0xB0, 0x1A, 12]).unwrap();
    s.send(&[0xB0, 0x1B, 5]).unwrap();
    let scratch = Tmp::new("learn-repeat");
    let out = scratch.0.join("profile.toml");
    capture_from(&mut m, &n, &["a", "b"], &["x", "y"], &out, Duration::from_secs(3)).unwrap();
    let text = std::fs::read_to_string(&out).unwrap();
    assert!(text.contains("0xb0:0x1a = x"), "{text}");
    assert!(text.contains("0xb0:0x1b = y"), "{text}");
}

#[test]
fn a_captured_profile_has_one_line_per_control() {
    let n = unique("profile");
    let mut m = MidiIn::open_virtual(&n).unwrap();
    let mut s = sender(&n);
    s.send(&[0x90, 0x00, 0x7F]).unwrap();
    s.send(&[0xB0, 0x1A, 3]).unwrap();
    let scratch = Tmp::new("learn-profile");
    let out = scratch.0.join("profile.toml");
    capture_from(&mut m, &n, &["play", "drive"], &["transport-toggle", "drive 0.0 2.0"], &out, Duration::from_secs(3)).unwrap();
    let text = std::fs::read_to_string(&out).unwrap();
    assert!(text.starts_with("# generated by midi-learn"), "{text}");
    assert!(text.contains(&format!("name = \"{n}\"")), "{text}");
    let bindings: Vec<_> = text.lines().filter(|l| l.contains(" = ") && !l.starts_with("name") && !l.starts_with('#')).collect();
    assert_eq!(bindings.len(), 2, "{text}");
    assert!(text.contains("0x90:0x00 = transport-toggle"));
    assert!(text.contains("0xb0:0x1a = drive 0.0 2.0"));
}
